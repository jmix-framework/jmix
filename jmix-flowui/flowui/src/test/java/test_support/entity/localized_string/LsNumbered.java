package test_support.entity.localized_string;

import io.jmix.core.entity.annotation.JmixGeneratedValue;
import io.jmix.core.entity.annotation.JmixId;
import io.jmix.core.metamodel.annotation.DependsOnProperties;
import io.jmix.core.metamodel.annotation.InstanceName;
import io.jmix.core.metamodel.annotation.JmixEntity;
import io.jmix.core.metamodel.annotation.LocalizedString;

import java.util.UUID;

/**
 * Carries an instance name made of a localized string and a number, so that a reference to it is sorted by
 * several properties in turn.
 */
@JmixEntity(name = "test_LsNumbered")
public class LsNumbered {

    @JmixId
    @JmixGeneratedValue
    private UUID id;

    @LocalizedString
    private String name;

    private Integer number;

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public Integer getNumber() {
        return number;
    }

    public void setNumber(Integer number) {
        this.number = number;
    }

    @InstanceName
    @DependsOnProperties({"name", "number"})
    public String getCaption() {
        return number + " " + name;
    }
}
